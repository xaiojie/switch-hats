import assert from 'node:assert/strict';
import {parseCatalog, parseLyrics, summarize} from './core.mjs';
const legacy=parseCatalog(JSON.stringify({name:'旧曲库',tracks:[{title:'测试曲',url:'song.mp3',album:'测试专辑',size:42}]}),'https://kiro.papaclaoud.top/library.json');
assert.equal(legacy.tracks[0].audio,'https://kiro.papaclaoud.top/song.mp3');
assert.equal(summarize(legacy.tracks).artist,0);
assert.equal(summarize(legacy.tracks).duration,0);
const modern=parseCatalog(JSON.stringify({version:1,tracks:[{id:'a',title:'测试曲',artist:'测试歌手',audio:'/歌曲.mp3',duration:123.4,cover:'/a.jpg',lyrics:'/a.lrc',format:'mp3'},{id:'b',title:'测试FLAC',audio:'/b.flac',format:'flac',switchPlayable:true}]}),'https://kiro.papaclaoud.top/library.json');
assert.equal(summarize(modern.tracks).playable,1);
assert.equal(summarize(modern.tracks).cover,1);
assert.equal(modern.tracks[0].cover,'https://kiro.papaclaoud.top/a.jpg');
assert.equal(modern.tracks[1].playable,false);
const m3u=parseCatalog('#EXTM3U\n#EXTGRP:测试专辑\n#EXTINF:123.5 tvg-logo="/a.jpg",测试歌手 - 测试曲\nsong.mp3','https://kiro.papaclaoud.top/library.m3u');
assert.equal(m3u.tracks[0].artist,'测试歌手');assert.equal(m3u.tracks[0].duration,123.5);assert.equal(m3u.tracks[0].album,'测试专辑');
assert.throws(()=>parseCatalog('<html>not a catalog</html>','https://kiro.papaclaoud.top/'));
assert.throws(()=>parseCatalog('#EXTM3U\n#EXT-X-TARGETDURATION:9\nchunk.ts','https://kiro.papaclaoud.top/'));
assert.throws(()=>parseCatalog(JSON.stringify({tracks:[{audio:'javascript:alert(1)'}]}),'https://kiro.papaclaoud.top/'));
const lrc=parseLyrics('[ar:测试歌手]\n[offset:100]\n[00:01.20][00:03.005]原创测试文本\n[00:02]第二行');
assert.deepEqual(lrc.lines.map(x=>x.time),[1.1,1.9,2.905]);assert.equal(lrc.synced,true);
assert.equal(parseLyrics('原创测试文本\n另一行').synced,false);
console.log('PASS catalog compatibility, real coverage, Switch format, safe URLs, M3U, LRC timing');
